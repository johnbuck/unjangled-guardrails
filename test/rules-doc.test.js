// Entry 3 (epic-rules-of-record): docs/rules.md is GENERATED — regeneration is the only write
// path, so this file proves the committed copy equals a fresh render byte for byte (hand edits
// cannot persist), that every live declaration is represented in it, and that the render
// refuses to ship behind a red conformance validator (a stale document must not pass).
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync, writeFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { renderRulesDoc } from "../tools/rules-doc.mjs";
import { THRESHOLDS, AD_PROBES, declaredCredentialPatterns } from "../tools/rules-conformance.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const committed = () => readFileSync(join(root, "docs", "rules.md"), "utf8");

test("rules-doc: the committed copy equals a fresh render, byte for byte", async () => {
  const fresh = await renderRulesDoc();
  // the write path: the renderer's output through writeFileSync lands identical to what the
  // renderer returned (the CLI writes the same way)
  const dir = mkdtempSync(join(tmpdir(), "rules-doc-test-"));
  const out = join(dir, "rules.md");
  writeFileSync(out, fresh.text);
  const fromDisk = readFileSync(out, "utf8");
  const doc = committed();
  assert.equal(fromDisk, fresh.text, "the renderer's write path is faithful to its output");
  assert.equal(doc, fresh.text, "docs/rules.md differs from a fresh render — regenerate it with node src/cli.js rules-doc (hand edits do not persist)");
  assert.ok(doc.startsWith("# Rules of record\n\n> GENERATED by `node src/cli.js rules-doc`"), "the generated-document header line is missing");
  assert.ok(/conformance validator \(`node src\/cli\.js rules-check`\) ran green immediately before rendering: \d+ rows, 0 failures/.test(doc),
    "the generation line does not record a green conformance run");
}, { timeout: 120000 });

test("rules-doc: every live declaration is represented in the committed document", async () => {
  const doc = committed();
  // thresholds — the shared declared table, one row per key
  for (const key of Object.keys(THRESHOLDS))
    assert.ok(doc.includes(`t.${key}`), `threshold ${key} is missing from docs/rules.md`);
  // Always-Deny — every registered probe and every pattern the module itself declares
  for (const p of AD_PROBES)
    assert.ok(doc.includes(p.id), `Always-Deny probe ${p.id} is missing from docs/rules.md`);
  for (const name of declaredCredentialPatterns())
    assert.ok(doc.includes(name), `module-declared credential-source pattern "${name}" is missing from docs/rules.md`);
  // the suggested defaults — every entry's pattern/path, effect and reason
  const example = JSON.parse(readFileSync(join(root, "examples", "user-policy.default.json"), "utf8"));
  for (const e of example.entries ?? []) {
    const target = e.kind === "dir" ? e.path : e.pattern;
    assert.ok(doc.includes(target), `defaults entry ${target} is missing from docs/rules.md`);
    assert.ok(doc.includes(`| ${e.effect ?? "allow"} |`), `defaults entry ${target} effect is missing from docs/rules.md`);
    if (e.reason) assert.ok(doc.includes(e.reason), `defaults entry ${target} carries its reason in docs/rules.md`);
  }
  // hygiene: the policy-store filename never renders (the suggested-defaults filename is a
  // different, already-tracked file and is fine to name)
  assert.ok(!/user-policy\.json/.test(doc), "the policy-store filename leaked into docs/rules.md");
});

test("rules-doc: the render refuses to ship behind a red validator (drift gate)", async () => {
  const red = async () => ({
    ok: false,
    rows: [],
    failures: ["thresholds().userP: declared 0.75, actual 0.85 (the threshold table drifted from its declaration)"],
    report: "unjangled-guardrails rules conformance — 0 rows, 1 failure(s)",
  });
  await assert.rejects(
    () => renderRulesDoc({ conformance: red }),
    (err) => {
      assert.match(err.message, /refuses to render/);
      assert.match(err.message, /rules-check/);
      assert.match(err.message, /userP/);  // the drift is named, not swallowed
      return true;
    },
  );
});
